export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
) {
  return String(
    new IntlMessageFormat((locale === "fi" ? fi : en)[key], locale).format(
      values,
    ),
  );
}
/** Localise an exact decimal string without rounding across a regulatory threshold. */
export function formatDecimal(value: string, locale: Locale): string {
  const separator = locale === "fi" ? "," : ".";
  if (/^[+-]?(?:\d+(?:\.\d*)?|\.\d+)[eE][+-]?\d+$/.test(value))
    return value.replace(".", separator);
  if (!/^[+-]?(?:\d+(?:\.\d*)?|\.\d+)$/.test(value)) return value;
  const negative = value.startsWith("-");
  const [integer, fraction] = value.replace(/^[+-]/, "").split(".");
  const grouped = new Intl.NumberFormat(
    locale === "fi" ? "fi-FI" : "en-GB",
  ).format(BigInt(integer || "0"));
  return `${negative ? "−" : ""}${grouped}${fraction !== undefined ? separator + fraction : ""}`;
}
export const formatNumber = (value: number, locale: Locale) =>
  formatDecimal(String(value), locale);
export const formatDate = (date: string, locale: Locale) =>
  new Intl.DateTimeFormat(locale === "fi" ? "fi-FI" : "en-GB", {
    dateStyle: "medium",
    timeZone: "UTC",
  }).format(new Date(date));
